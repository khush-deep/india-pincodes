<?php

/**
 * Builds data/{first 3 digits}.php from India Post's "All India Pincode Directory" CSV.
 * Run from a clone of this repo: php bin/generate-pincode-data.php <csv file> [<output folder>]
 *
 * Getting the CSV: download it from https://www.data.gov.in/resource/all-india-pincode-directory-till-last-month
 * (the site asks for a name, email and captcha, so it's done by hand in the browser).
 */

use Khush\IndiaPincodes\IndiaState;
use Khush\IndiaPincodes\PincodeLookup;

require __DIR__ . '/../vendor/autoload.php';

const COLUMN_OFFICE   = 'officename';
const COLUMN_PIN      = 'pincode';
const COLUMN_TYPE     = 'officetype';
const COLUMN_DELIVERY = 'delivery';
const COLUMN_DISTRICT = 'district';
const COLUMN_STATE    = 'statename';
const COLUMNS         = [COLUMN_OFFICE, COLUMN_PIN, COLUMN_TYPE, COLUMN_DELIVERY, COLUMN_DISTRICT, COLUMN_STATE];

const DELIVERY_VALUES = ['Delivery' => true, 'Non Delivery' => false];
const OFFICE_TYPES    = [PincodeLookup::TYPE_HEAD_OFFICE, PincodeLookup::TYPE_SUB_OFFICE, PincodeLookup::TYPE_BRANCH_OFFICE];

// The source writes a missing district or state as "NA".
const MISSING_VALUE = 'NA';

// "Kothimir B.O", "Manaitand SO", "DuppalliB.O" - the suffix repeats the office type, which is its own field.
// Only the letter matching the row's type is removed, so "NDC Coimbatore HO" on a sub office keeps its "HO".
const OFFICE_TYPE_SUFFIX_LETTERS = [
    PincodeLookup::TYPE_HEAD_OFFICE   => 'H',
    PincodeLookup::TYPE_SUB_OFFICE    => '[SP]',
    PincodeLookup::TYPE_BRANCH_OFFICE => 'B',
];

// Words title case gets wrong. Checked by hand against every district in the source.
const DISTRICT_LOWER_WORDS = ['and'];
const DISTRICT_ACRONYMS    = ['Ntr' => 'NTR', 'Spsr' => 'SPSR'];

const FILE_HEADER_COMMENT = 'Generated by bin/generate-pincode-data.php - do not edit by hand. Source and licence: NOTICE.md';

main($argv);

function main(array $argv): void
{
    if (isset($argv[1]) === false)
    {
        fail('Usage: php bin/generate-pincode-data.php <csv file> [<output folder>]');
    }

    $csvPath = $argv[1];
    $output  = rtrim($argv[2] ?? dirname(__DIR__) . '/data', '/');

    if (is_file($csvPath) === false)
    {
        fail('Missing source file ' . $csvPath);
    }

    [$entries, $skipped] = readRows($csvPath);

    writeFiles($output, $entries);

    echo count($entries) . ' PINs written, ' . $skipped . " rows skipped\n";
}

function readRows(string $csvPath): array
{
    $handle = fopen($csvPath, 'r');

    if ($handle === false)
    {
        fail('Cannot read ' . $csvPath);
    }

    $positions  = columnPositions(fgetcsv($handle, null, ',', '"', ''));
    $stateCodes = stateCodesByName();
    $entries    = [];
    $skipped    = 0;
    $line       = 1;

    while (($row = fgetcsv($handle, null, ',', '"', '')) !== false)
    {
        $line++;

        // fgetcsv() reads a blank line as [null].
        if ($row === [null])
        {
            continue;
        }

        $value = fn (string $column) => cleanSpaces($row[$positions[$column]] ?? '', $line);
        $pin   = $value(COLUMN_PIN);

        // A row without a valid PIN can't be looked up, so it's left out.
        if (preg_match('/^[1-9]\d{5}$/', $pin) !== 1)
        {
            $skipped++;

            continue;
        }

        $type   = officeType($value(COLUMN_TYPE), $line);
        $office = [
            cleanOfficeName($value(COLUMN_OFFICE), $type),
            $type,
            deliveryFlag($value(COLUMN_DELIVERY), $line),
            districtName($value(COLUMN_DISTRICT)),
            stateCode($value(COLUMN_STATE), $stateCodes, $line),
        ];

        // The source lists a few offices twice under the same PIN.
        $entries[$pin][implode("\0", array_map('strval', $office))] = $office;
    }

    fclose($handle);

    return [sortEntries($entries), $skipped];
}

function columnPositions(array|false $header): array
{
    if ($header === false)
    {
        fail('The CSV is empty');
    }

    // The download may start with a byte order mark.
    $header    = array_map(fn (string $name) => strtolower(trim(preg_replace('/^\xEF\xBB\xBF/', '', $name))), $header);
    $positions = [];

    foreach (COLUMNS as $column)
    {
        $position = array_search($column, $header, true);

        if ($position === false)
        {
            fail('Missing column in the CSV: ' . $column);
        }

        $positions[$column] = $position;
    }

    return $positions;
}

/**
 * Collapses runs of spaces, including the non-breaking spaces some rows carry, and trims.
 */
function cleanSpaces(string $value, int $line): string
{
    $cleaned = preg_replace('/[\s\x{00A0}]+/u', ' ', $value);

    if ($cleaned === null)
    {
        fail('Invalid UTF-8 on line ' . $line);
    }

    return trim($cleaned);
}

/**
 * Repeats until nothing changes, because some names carry the suffix twice, i.e. "Relawan  B.O. B.O".
 * A glued suffix ("DuppalliB.O") must be capitals after a lowercase letter or ")", so "Pobo" and
 * initials like "D.S.O" stay as they are.
 */
function cleanOfficeName(string $name, string $type): string
{
    $letter = OFFICE_TYPE_SUFFIX_LETTERS[$type];

    do
    {
        $previous = $name;
        $name     = rtrim(preg_replace('/\s+' . $letter . '\.?\s?O\.?$/i', '', $name));
        $name     = rtrim(preg_replace('/(?<=[a-z)])' . $letter . '(?:\.O|O)\.?$/', '', $name));
    }
    while ($name !== $previous);

    return $name;
}

function officeType(string $type, int $line): string
{
    // An unknown value means the source changed, so stop and let a person look rather than guess.
    if (in_array($type, OFFICE_TYPES, true) === false)
    {
        fail('Unknown office type "' . $type . '" on line ' . $line);
    }

    return $type;
}

function deliveryFlag(string $delivery, int $line): bool
{
    if (isset(DELIVERY_VALUES[$delivery]) === false)
    {
        fail('Unknown delivery value "' . $delivery . '" on line ' . $line);
    }

    return DELIVERY_VALUES[$delivery];
}

/**
 * Most districts come in capitals ("KUMURAM BHEEM ASIFABAD") and the newer ones in title case
 * ("Bapatla"), so only the all-capitals ones are converted. Mixed-case names are kept as published,
 * which also keeps initials like "Y.S.R." intact.
 */
function districtName(string $district): ?string
{
    if (($district === '') || ($district === MISSING_VALUE))
    {
        return null;
    }

    if (strtoupper($district) !== $district)
    {
        return $district;
    }

    // "." keeps initials like "Y.S.R." in capitals.
    $words = explode(' ', ucwords(strtolower($district), " -(."));

    foreach ($words as $index => $word)
    {
        if (($index > 0) && (in_array(strtolower($word), DISTRICT_LOWER_WORDS, true) === true))
        {
            $words[$index] = strtolower($word);
        }

        $words[$index] = DISTRICT_ACRONYMS[$words[$index]] ?? $words[$index];
    }

    return implode(' ', $words);
}

function stateCode(string $state, array $stateCodes, int $line): ?string
{
    if (($state === '') || ($state === MISSING_VALUE))
    {
        return null;
    }

    $code = $stateCodes[normaliseStateName($state)] ?? null;

    // A new or renamed state needs adding to IndiaState first.
    if ($code === null)
    {
        fail('Unknown state "' . $state . '" on line ' . $line . ' - add it to src/IndiaState.php');
    }

    return $code;
}

function stateCodesByName(): array
{
    $codes = [];

    foreach (IndiaState::NAMES_BY_CODE as $code => $name)
    {
        $codes[normaliseStateName($name)] = $code;
    }

    return $codes;
}

/**
 * "THE DADRA AND NAGAR HAVELI AND DAMAN AND DIU" and "Jammu & Kashmir" match the IndiaState names.
 */
function normaliseStateName(string $name): string
{
    $name = strtolower(trim(str_replace('&', ' and ', $name)));
    $name = preg_replace('/\s+/', ' ', $name);

    return preg_replace('/^the /', '', $name);
}

/**
 * PINs in order and each PIN's offices by name, so a data refresh shows only real changes in a diff.
 */
function sortEntries(array $entries): array
{
    ksort($entries, SORT_STRING);

    foreach ($entries as $pin => $offices)
    {
        $offices = array_values($offices);

        // The whole office breaks ties, i.e. "Kalan" and "KALAN", so the order never depends on the CSV's row order.
        usort($offices, fn (array $a, array $b) => [strtolower($a[0]), $a[1], $a] <=> [strtolower($b[0]), $b[1], $b]);

        $entries[$pin] = $offices;
    }

    return $entries;
}

function writeFiles(string $folder, array $entries): void
{
    if (is_dir($folder) === false)
    {
        if (mkdir($folder, 0755, true) === false)
        {
            fail('Cannot create ' . $folder);
        }
    }

    // Only the generated prefix files, so a wrong output folder loses nothing else.
    foreach (glob($folder . '/[0-9][0-9][0-9].php') as $oldFile)
    {
        unlink($oldFile);
    }

    $byPrefix = [];

    foreach ($entries as $pin => $offices)
    {
        $byPrefix[substr((string) $pin, 0, 3)][(string) $pin] = $offices;
    }

    foreach ($byPrefix as $prefix => $prefixEntries)
    {
        // The CSV is fully read before anything is deleted, so only a disk error can leave the folder half written.
        if (file_put_contents($folder . '/' . $prefix . '.php', renderFile($prefixEntries)) === false)
        {
            fail('Cannot write ' . $folder . '/' . $prefix . '.php - run the generator again');
        }
    }
}

function renderFile(array $entries): string
{
    $lines = [
        '<?php',
        '',
        '// ' . FILE_HEADER_COMMENT,
        '// Each office: [' . implode(', ', PincodeLookup::FIELDS) . ']',
        '',
        'return [',
    ];

    foreach ($entries as $pin => $offices)
    {
        $lines[] = '    ' . var_export((string) $pin, true) . ' => [';

        foreach ($offices as $office)
        {
            $lines[] = '        [' . implode(', ', array_map(fn ($value) => var_export($value, true), $office)) . '],';
        }

        $lines[] = '    ],';
    }

    $lines[] = '];';

    return implode("\n", $lines) . "\n";
}

function fail(string $message): never
{
    fwrite(STDERR, $message . "\n");

    exit(1);
}
